import nodemailer, { Transporter } from 'nodemailer';

export interface SendMailParams {
  smtpHost: string;
  smtpPort: number;
  smtpUser: string;
  smtpPass: string;
  fromName: string;
  fromEmail: string;
  to: string;
  subject: string;
  text: string;
  html?: string;
}

export class SmtpService {
  private static transporters: Map<string, Transporter> = new Map();

  private static getTransporter(host: string, port: number, user: string, pass: string): Transporter {
    const key = `${user}@${host}:${port}`;
    if (!this.transporters.has(key)) {
      const transporter = nodemailer.createTransport({
        host,
        port,
        secure: port === 465,
        auth: {
          user,
          pass,
        },
      });
      this.transporters.set(key, transporter);
    }
    return this.transporters.get(key)!;
  }

  /**
   * Dispatches email via SMTP and extracts Ethereal Preview URL
   */
  static async sendEmail(params: SendMailParams): Promise<{ messageId: string; etherealUrl: string | null }> {
    const transporter = this.getTransporter(
      params.smtpHost,
      params.smtpPort,
      params.smtpUser,
      params.smtpPass
    );

    const info = await transporter.sendMail({
      from: `"${params.fromName}" <${params.fromEmail}>`,
      to: params.to,
      subject: params.subject,
      text: params.text,
      html: params.html || params.text.replace(/\n/g, '<br/>'),
    });

    // Obtain preview URL generated by Ethereal fake SMTP
    const previewUrl = nodemailer.getTestMessageUrl(info);
    const etherealUrl = previewUrl ? previewUrl.toString() : null;

    if (etherealUrl) {
      console.log(`✉️ Email dispatched to ${params.to}! View live at Ethereal: ${etherealUrl}`);
    }

    return {
      messageId: info.messageId,
      etherealUrl,
    };
  }
}
